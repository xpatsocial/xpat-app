/** Sort visas by attractiveness score (highest first) */
export const getByAttractiveness = () =>
  [...nomadVisas].sort((a, b) => b.attractiveness - a.attractiveness);

/** Get only visas launched in 2025 or 2026 */
export const getNewestPrograms = () =>
  nomadVisas.filter((v) => v.launchYear >= 2025);

/** Get visas by region */
export const getByRegion = (region: NomadVisa['region']) =>
  nomadVisas.filter((v) => v.region === region);

/** Get visas affordable for a given monthly income */
export const getAffordable = (monthlyIncome: number) =>
  nomadVisas.filter(
    (v) => v.incomeMonthly <= monthlyIncome || v.incomeMonthly === 0
  );

/** Get tax-free or no-local-tax visas */
export const getTaxFriendly = () =>
  nomadVisas.filter(
    (v) =>
      v.taxImplication.toLowerCase().includes('zero') ||
      v.taxImplication.toLowerCase().includes('no tax') ||
      v.taxImplication.toLowerCase().includes('0%') ||
      v.taxImplication.toLowerCase().includes('no local tax') ||
      v.taxImplication.toLowerCase().includes('territorial')
  );

/** Get easiest application visas (rating 4+) */
export const getEasiestApplications = () =>
  nomadVisas.filter((v) => v.easeOfApp >= 4);

/** Get most popular visas (rating 4+) */
export const getMostPopular = () =>
  nomadVisas.filter((v) => v.popularity >= 4);

/** Get all unique regions */
export const getRegions = (): NomadVisa['region'][] => [
  'Europe',
  'Caribbean',
  'Latin America',
  'Asia',
  'Middle East',
  'Africa',
];

/** Summary stats */
export const getStats = () => ({
  totalCountries: nomadVisas.length,
  newestPrograms: getNewestPrograms().length,
  taxFreeOptions: getTaxFriendly().length,
  regionCounts: getRegions().reduce(
    (acc, r) => ({ ...acc, [r]: getByRegion(r).length }),
    {} as Record<string, number>
  ),
  lowestIncomeRequirement: [...nomadVisas]
    .filter((v) => v.incomeMonthly > 0)
    .sort((a, b) => a.incomeMonthly - b.incomeMonthly)[0],
  highestAttractiveness: getByAttractiveness()[0],
});
